import AppKit
import SwiftUI
import Combine

@MainActor
public final class ClipboardManager: ObservableObject {
    public static let shared = ClipboardManager()
    
    @Published public private(set) var items: [ClipboardItem] = []
    @Published public var searchText: String = ""
    
    private var lastChangeCount: Int = 0
    private var timer: Timer?
    private let storageURL: URL
    
    // Private clipboard marker types to ignore automatically
    private let ignoredTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.dsteltz.MacPass")
    ]
    
    private init() {
        let appSupport = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        let dir = appSupport.appendingPathComponent("ApexNotch", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        self.storageURL = dir.appendingPathComponent("clipboard_history.json")
        
        self.lastChangeCount = NSPasteboard.general.changeCount
        loadHistory()
        startMonitoring()
    }
    
    public var filteredItems: [ClipboardItem] {
        if searchText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return items
        }
        return items.filter { item in
            item.content.localizedCaseInsensitiveContains(searchText) ||
            item.type.rawValue.localizedCaseInsensitiveContains(searchText)
        }
    }
    
    public func startMonitoring() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.8, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkPasteboard()
            }
        }
    }
    
    public func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }
    
    private func checkPasteboard() {
        guard !UserPreferences.shared.clipboardMonitoringPaused else { return }
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        
        // Check for password manager transient types
        if let types = pasteboard.types {
            for ignored in ignoredTypes {
                if types.contains(ignored) {
                    return
                }
            }
        }
        
        // Read text/string content
        if let string = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !string.isEmpty {
            processCopiedString(string)
        }
    }
    
    private func processCopiedString(_ string: String) {
        // Detect sensitive content
        let (isSecret, secretDesc) = detectSecret(in: string)
        if isSecret && !UserPreferences.shared.clipboardDetectSecrets {
            // User opted out of storing secrets completely
            return
        }
        
        let contentType = determineContentType(for: string)
        
        // Remove existing identical non-pinned item to avoid duplicate clutter
        items.removeAll(where: { $0.content == string && !$0.isPinned })
        
        let newItem = ClipboardItem(
            content: string,
            type: contentType,
            timestamp: Date(),
            isPinned: false,
            isSecret: isSecret,
            secretDescription: secretDesc
        )
        
        items.insert(newItem, at: 0)
        
        // Enforce history limit
        let limit = UserPreferences.shared.clipboardLimit
        let nonPinnedCount = items.filter { !$0.isPinned }.count
        if nonPinnedCount > limit {
            if let lastNonPinnedIndex = items.lastIndex(where: { !$0.isPinned }) {
                items.remove(at: lastNonPinnedIndex)
            }
        }
        
        saveHistory()
    }
    
    private func determineContentType(for string: String) -> ClipboardContentType {
        if let url = URL(string: string), url.scheme != nil, UIApplicationCanOpenURLString(string) {
            return .url
        }
        if string.hasPrefix("#") && (string.count == 7 || string.count == 9 || string.count == 4) {
            return .color
        }
        if string.contains("func ") || string.contains("import ") || string.contains("const ") || string.contains("class ") || string.contains("<div>") {
            return .code
        }
        return .text
    }
    
    private func UIApplicationCanOpenURLString(_ str: String) -> Bool {
        return str.hasPrefix("http://") || str.hasPrefix("https://") || str.hasPrefix("ftp://")
    }
    
    public func detectSecret(in text: String) -> (Bool, String?) {
        // GitHub personal access tokens
        if text.range(of: #"ghp_[A-Za-z0-9]{36}"#, options: .regularExpression) != nil {
            return (true, "GitHub Token")
        }
        // OpenAI API keys
        if text.range(of: #"sk-[A-Za-z0-9]{32,}"#, options: .regularExpression) != nil {
            return (true, "OpenAI API Key")
        }
        // AWS Access Keys
        if text.range(of: #"AKIA[0-9A-Z]{16}"#, options: .regularExpression) != nil {
            return (true, "AWS Access Key")
        }
        // Private keys
        if text.contains("-----BEGIN PRIVATE KEY-----") || text.contains("-----BEGIN RSA PRIVATE KEY-----") {
            return (true, "Private Encryption Key")
        }
        // Bearer tokens
        if text.lowercased().hasPrefix("bearer eyj") {
            return (true, "Bearer JWT Token")
        }
        return (false, nil)
    }
    
    public func copyToClipboard(item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(item.content, forType: .string)
        self.lastChangeCount = pasteboard.changeCount
        AppState.shared.showToast("Copied to clipboard!")
    }
    
    public func togglePin(id: UUID) {
        if let index = items.firstIndex(where: { $0.id == id }) {
            items[index].isPinned.toggle()
            saveHistory()
            AppState.shared.showToast(items[index].isPinned ? "Snippet pinned" : "Snippet unpinned")
        }
    }
    
    public func removeItem(id: UUID) {
        items.removeAll(where: { $0.id == id })
        saveHistory()
    }
    
    public func clearHistory() {
        items.removeAll(where: { !$0.isPinned })
        saveHistory()
        AppState.shared.showToast("Cleared clipboard history")
    }
    
    public func clearAllIncludingPinned() {
        items.removeAll()
        saveHistory()
        AppState.shared.showToast("Cleared all clipboard items")
    }
    
    // MARK: - Persistence
    private func saveHistory() {
        guard !UserPreferences.shared.clipboardMemoryOnly else { return }
        if let data = try? JSONEncoder().encode(items) {
            try? data.write(to: storageURL)
        }
    }
    
    private func loadHistory() {
        guard !UserPreferences.shared.clipboardMemoryOnly else { return }
        guard let data = try? Data(contentsOf: storageURL),
              let loaded = try? JSONDecoder().decode([ClipboardItem].self, from: data) else { return }
        self.items = loaded
    }
}
